/* eslint-enable quote-props */

function main () {
  const outDir = path.join(__dirname, "..", "translations");
  fs.mkdirSync(outDir, { recursive: true });

  const missing = [];
  for (const [lang, table] of Object.entries(TRANSLATIONS)) {
    const ordered = {};
    for (const key of KEYS) {
      if (!(key in table)) missing.push(`${lang}.${key}`);
      ordered[key] = table[key] ?? TRANSLATIONS.en[key];
    }
    const file = path.join(outDir, `${lang}.json`);
    fs.writeFileSync(file, `${JSON.stringify(ordered, null, 2)}\n`, "utf8");
  }

  if (missing.length) {
    console.error(`Missing keys: ${missing.join(", ")}`);
    process.exitCode = 1;
    return;
  }
  console.log(`Wrote ${Object.keys(TRANSLATIONS).length} translation files with ${KEYS.length} keys each.`);
}

if (require.main === module) main();

module.exports = { KEYS, TRANSLATIONS };
